#!/usr/bin/env python3
"""Write frontend/.env.aws from the CloudFormation stack outputs.

Usage: python scripts/deployment/write_frontend_env.py --stack-name serverless-notes-dev
The generated file contains identifiers only (no secrets) and is git-ignored.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import boto3

OUTPUT_TO_ENV = {
    "ApiBaseUrl": "VITE_API_BASE_URL",
    "Region": "VITE_AWS_REGION",
    "UserPoolId": "VITE_COGNITO_USER_POOL_ID",
    "UserPoolClientId": "VITE_COGNITO_CLIENT_ID",
    "CognitoDomain": "VITE_COGNITO_DOMAIN",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stack-name", default="serverless-notes-dev")
    parser.add_argument("--region", default=os.environ.get("AWS_REGION", "eu-central-1"))
    parser.add_argument("--origin", default="http://localhost:5173")
    args = parser.parse_args()

    cloudformation = boto3.client("cloudformation", region_name=args.region)
    stack = cloudformation.describe_stacks(StackName=args.stack_name)["Stacks"][0]
    outputs = {o["OutputKey"]: o["OutputValue"] for o in stack.get("Outputs", [])}

    missing = sorted(set(OUTPUT_TO_ENV) - set(outputs))
    if missing:
        raise SystemExit(f"Stack {args.stack_name} is missing outputs: {', '.join(missing)}")

    lines = ["# Generated by scripts/deployment/write_frontend_env.py - do not commit", "VITE_APP_MODE=aws"]
    lines += [f"{env}={outputs[key]}" for key, env in OUTPUT_TO_ENV.items()]
    lines += [
        f"VITE_OAUTH_REDIRECT_URI={args.origin}/auth/callback",
        f"VITE_OAUTH_LOGOUT_URI={args.origin}/",
    ]
    target = Path(__file__).resolve().parents[2] / "frontend" / ".env.aws"
    target.write_text("\n".join(lines) + "\n")
    print(f"Wrote {target}\nStart the app against AWS with:  cd frontend && npm run dev:aws")


if __name__ == "__main__":
    main()
