#!/usr/bin/env python3
"""Write the frontend's AWS environment file from the CloudFormation stack outputs.

    python scripts/deployment/write_frontend_env.py --stack-name serverless-notes-dev
        -> frontend/.env.aws     (npm run dev:aws on localhost)
    python scripts/deployment/write_frontend_env.py --target hosted
        -> frontend/.env.hosted  (npm run build:hosted, published to CloudFront)

Local development: the browser calls http://localhost:5173/api/... and the Vite dev server
forwards those requests to API Gateway (DEV_API_PROXY_TARGET). The calls are same-origin,
so they work although the API's CORS origin is the hosted CloudFront URL.

Hosted build: the browser calls API Gateway directly (CORS origin = CloudFront URL). The
OAuth redirect/logout URIs are left unset so the app derives them from its own origin.

The generated files contain identifiers only (no secrets) and are git-ignored.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import boto3

OUTPUT_TO_ENV = {
    "ApiBaseUrl": "VITE_API_BASE_URL",
    "Region": "VITE_AWS_REGION",
    "UserPoolId": "VITE_COGNITO_USER_POOL_ID",
    "UserPoolClientId": "VITE_COGNITO_CLIENT_ID",
    "CognitoDomain": "VITE_COGNITO_DOMAIN",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stack-name", default="serverless-notes-dev")
    parser.add_argument("--region", default=os.environ.get("AWS_REGION", "eu-north-1"))
    parser.add_argument("--origin", default="http://localhost:5173")
    parser.add_argument("--target", choices=["local", "hosted"], default="local")
    args = parser.parse_args()

    cloudformation = boto3.client("cloudformation", region_name=args.region)
    stack = cloudformation.describe_stacks(StackName=args.stack_name)["Stacks"][0]
    outputs = {o["OutputKey"]: o["OutputValue"] for o in stack.get("Outputs", [])}

    missing = sorted(set(OUTPUT_TO_ENV) - set(outputs))
    if missing:
        raise SystemExit(f"Stack {args.stack_name} is missing outputs: {', '.join(missing)}")

    values = {env: outputs[key] for key, env in OUTPUT_TO_ENV.items()}
    lines = [
        "# Generated by scripts/deployment/write_frontend_env.py - do not commit",
        "VITE_APP_MODE=aws",
    ]
    frontend = Path(__file__).resolve().parents[2] / "frontend"
    if args.target == "local":
        # Same-origin path served by the Vite dev-server proxy (frontend/vite.config.ts).
        lines.append(f"DEV_API_PROXY_TARGET={values['VITE_API_BASE_URL']}")
        values["VITE_API_BASE_URL"] = f"{args.origin}/api"
    lines += [f"{env}={value}" for env, value in values.items()]
    if args.target == "local":
        lines += [
            f"VITE_OAUTH_REDIRECT_URI={args.origin}/auth/callback",
            f"VITE_OAUTH_LOGOUT_URI={args.origin}/",
        ]
        target = frontend / ".env.aws"
        hint = "Start the app against AWS with:  cd frontend && npm run dev:aws"
    else:
        target = frontend / ".env.hosted"
        hint = "Build the hosted frontend with:  cd frontend && npm run build:hosted"
    target.write_text("\n".join(lines) + "\n")
    print(f"Wrote {target}\n{hint}")


if __name__ == "__main__":
    main()
